-- ============================================================================
-- 表名: SUBJECT_MST - 科目信息主表
-- 表名: TEACHER_MST - 教师信息主表  
-- 表名: SCORE_REC - 成绩记录表
-- ============================================================================

-- 科目表
CREATE TABLE SUBJECT_MST (
    SUBJECT_CD         NUMBER(5,0)       NOT NULL,
    SUBJECT_NAME       NVARCHAR2(100)    NOT NULL,
    SUBJECT_KANA       NVARCHAR2(200)    NOT NULL,
    SUBJECT_TYPE       NUMBER(1,0)       NOT NULL,
    CREDIT             NUMBER(2,0)       DEFAULT 0,
    MAX_SCORE          NUMBER(3,0)       DEFAULT 100,
    PASS_SCORE         NUMBER(3,0)       DEFAULT 60,
    TEACHER_CD         NUMBER(10,0)      ,
    SEMESTER           NUMBER(1,0)       ,
    DELETE_FLG         NUMBER(1,0)       DEFAULT 0,
    REC_CREATE_TANTO_CD CHAR(12),
    REC_CREATE_DATE     CHAR(23),
    REC_CREATE_WS       NVARCHAR2(63),
    REC_UPDATE_TANTO_CD CHAR(12),
    REC_UPDATE_DATE     CHAR(23),
    REC_UPDATE_WS       NVARCHAR2(63),
    REC_UPDATE_KBN      CHAR(2),
    CONSTRAINT SUBJECT_MST_PK PRIMARY KEY (SUBJECT_CD) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 教师表
CREATE TABLE TEACHER_MST (
    TEACHER_CD         NUMBER(10,0)     NOT NULL,
    TEACHER_NAME       NVARCHAR2(100)   NOT NULL,
    TEACHER_KANA       NVARCHAR2(200)   NOT NULL,
    GENDER             NUMBER(1,0)      NOT NULL,
    DEPT_CD            NUMBER(5,0)      ,
    PHONE              NVARCHAR2(20)    ,
    EMAIL              NVARCHAR2(100)   ,
    HIRE_DATE          NUMBER(8,0)      ,
    STATUS             NUMBER(1,0)      DEFAULT 0,
    DELETE_FLG         NUMBER(1,0)      DEFAULT 0,
    REC_CREATE_TANTO_CD CHAR(12),
    REC_CREATE_DATE     CHAR(23),
    REC_UPDATE_TANTO_CD CHAR(12),
    REC_UPDATE_DATE     CHAR(23),
    CONSTRAINT TEACHER_MST_PK PRIMARY KEY (TEACHER_CD) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 成绩表
CREATE TABLE SCORE_REC (
    STUDENT_NO          NUMBER(10,0)     NOT NULL,
    SUBJECT_CD          NUMBER(5,0)      NOT NULL,
    EXAM_DATE           NUMBER(8,0)       NOT NULL,
    EXAM_TYPE           NUMBER(1,0)       NOT NULL,
    SCORE               NUMBER(5,2)       ,
    SCORE_RANK          NUMBER(5,0)       ,
    GRADE_LEVEL         NUMBER(1,0)       ,
    IS_PASS             NUMBER(1,0)       ,
    REMARK              NVARCHAR2(500)    ,
    REC_CREATE_TANTO_CD CHAR(12),
    REC_CREATE_DATE     CHAR(23),
    REC_CREATE_WS       NVARCHAR2(63),
    REC_UPDATE_TANTO_CD CHAR(12),
    REC_UPDATE_DATE     CHAR(23),
    REC_UPDATE_WS       NVARCHAR2(63),
    REC_UPDATE_KBN      CHAR(2),
    CONSTRAINT SCORE_REC_PK PRIMARY KEY (STUDENT_NO, SUBJECT_CD, EXAM_DATE, EXAM_TYPE) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 工作表
CREATE TABLE WK_SCORE_REPORT (
    ROW_NO              NUMBER(10,0)     NOT NULL,
    NO                  NUMBER(38,0)     ,
    NENDO               NVARCHAR2(1000)  ,
    STUDENT_NO          NVARCHAR2(1000)  ,
    STUDENT_NAME        NVARCHAR2(1000)  ,
    STUDENT_KANA        NVARCHAR2(1000)  ,
    GENDER              NVARCHAR2(1000)  ,
    GRADE               NVARCHAR2(1000)  ,
    CLASS_NO            NVARCHAR2(1000)  ,
    SUBJECT_NAME        NVARCHAR2(1000)  ,
    SUBJECT_CD          NVARCHAR2(1000)  ,
    TOTAL_SCORE         NVARCHAR2(1000)  ,
    AVERAGE_SCORE       NVARCHAR2(1000)  ,
    PASS_COUNT          NVARCHAR2(1000)  ,
    FAIL_COUNT          NVARCHAR2(1000)  ,
    WSNUM               NVARCHAR2(63)    ,
    BATCHKBN            NUMBER(2,0)      ,
    JOBNUM              NUMBER(38,0)     ,
    CONSTRAINT WK_SCORE_REPORT_PK PRIMARY KEY (ROW_NO) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 配置表
CREATE TABLE SYSTEM_CONFIG (
    CONFIG_CD          NVARCHAR2(100)    NOT NULL,
    CONFIG_NAME        NVARCHAR2(200)    NOT NULL,
    CONFIG_VALUE       NVARCHAR2(1000)  ,
    CONFIG_TYPE        NUMBER(2,0)      DEFAULT 1,
    SORT_ORDER         NUMBER(5,0)      DEFAULT 0,
    DESCRIPTION        NVARCHAR2(500)   ,
    DELETE_FLG         NUMBER(1,0)      DEFAULT 0,
    CONSTRAINT SYSTEM_CONFIG_PK PRIMARY KEY (CONFIG_CD) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 附件表(BLOB)
CREATE TABLE ATTACHMENT_STORAGE (
    ROW_NUMBER          NUMBER(9,0)      NOT NULL,
    DATA                BLOB             ,
    FILE_ID             NVARCHAR2(255)   ,
    FILE_NAME           NVARCHAR2(255)   NOT NULL,
    FILE_SIZE           NUMBER(15,0)    ,
    FILE_TYPE           NVARCHAR2(100)  ,
    FILE_UPDATE_TIME    CHAR(23)        ,
    CONSTRAINT ATTACHMENT_STORAGE_PK PRIMARY KEY (ROW_NUMBER) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 日志表
CREATE TABLE PROCESS_LOG (
    LOG_ID             NUMBER(20,0)     NOT NULL,
    JOBNUM             NUMBER(38,0)     ,
    PROCESS_NAME       NVARCHAR2(100)   ,
    STEP_NO            NUMBER(5,0)      ,
    LOG_LEVEL          NUMBER(1,0)      DEFAULT 0,
    LOG_MESSAGE        NVARCHAR2(2000)  ,
    SQLCODE            NUMBER(10,0)     ,
    SQLERRM            NVARCHAR2(500)   ,
    TANTO_CD           CHAR(12)        ,
    WS_NUM             NVARCHAR2(63)    ,
    LOG_DATE           CHAR(23)         ,
    CONSTRAINT PROCESS_LOG_PK PRIMARY KEY (LOG_ID) USING INDEX TABLESPACE USERS
) TABLESPACE USERS NOCACHE LOGGING;

-- 临时表(批次处理用)
CREATE GLOBAL TEMPORARY TABLE TEMP_SCORE_BATCH (
    BATCH_ID           NUMBER(10,0)     NOT NULL,
    STUDENT_NO          NUMBER(10,0)     NOT NULL,
    SUBJECT_CD          NUMBER(5,0)      NOT NULL,
    SCORE               NUMBER(5,2)      ,
    STATUS              NUMBER(1,0)      DEFAULT 0,
    ERROR_MSG           NVARCHAR2(500)  ,
    CONSTRAINT TEMP_SCORE_BATCH_PK PRIMARY KEY (BATCH_ID) USING INDEX TABLESPACE USERS
) ON COMMIT PRESERVE ROWS TABLESPACE USERS;
