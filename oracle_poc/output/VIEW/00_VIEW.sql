CREATE OR REPLACE VIEW V_STUDENT_SCORE AS
SELECT
    S.STUDENT_NO,
    S.STUDENT_NAME,
    S.STUDENT_KANA,
    S.GENDER,
    S.GRADE,
    S.CLASS_NO,
    SB.SUBJECT_CD,
    SB.SUBJECT_NAME,
    SB.SUBJECT_TYPE,
    SB.CREDIT,
    SC.EXAM_DATE,
    SC.EXAM_TYPE,
    SC.SCORE,
    SC.GRADE_LEVEL,
    SC.IS_PASS,
    CASE SC.EXAM_TYPE
        WHEN 1 THEN '期中考试'
        WHEN 2 THEN '期末考试'
        WHEN 3 THEN '补考'
        WHEN 4 THEN '平时'
        ELSE '其他'
    END AS EXAM_TYPE_NAME,
    CASE
        WHEN SC.SCORE >= 90 THEN 'A'
        WHEN SC.SCORE >= 80 THEN 'B'
        WHEN SC.SCORE >= 70 THEN 'C'
        WHEN SC.SCORE >= 60 THEN 'D'
        ELSE 'F'
    END AS LETTER_GRADE,
    T.TEACHER_NAME,
    SB.PASS_SCORE
FROM STUDENT_MST S
CROSS JOIN SUBJECT_MST SB
LEFT JOIN SCORE_REC SC
  ON S.STUDENT_NO = SC.STUDENT_NO AND SB.SUBJECT_CD = SC.SUBJECT_CD
LEFT JOIN TEACHER_MST T
  ON SB.TEACHER_CD = T.TEACHER_CD
WHERE S.DELETE_FLG = 0
  AND SB.DELETE_FLG = 0;





CREATE OR REPLACE VIEW V_STUDENT_STATS AS
SELECT
    S.STUDENT_NO,
    S.STUDENT_NAME,
    S.GRADE,
    S.CLASS_NO,
    COUNT(SC.STUDENT_NO) AS EXAM_COUNT,
    SUM(SC.SCORE) AS TOTAL_SCORE,
    ROUND(AVG(SC.SCORE)::NUMERIC, 2) AS AVG_SCORE,
    MAX(SC.SCORE) AS MAX_SCORE,
    MIN(SC.SCORE) AS MIN_SCORE,
    SUM(CASE WHEN SC.IS_PASS = 1 THEN 1 ELSE 0 END) AS PASS_COUNT,
    SUM(CASE WHEN SC.IS_PASS = 0 THEN 1 ELSE 0 END) AS FAIL_COUNT,
    ROUND(SUM(CASE WHEN SC.IS_PASS = 1 THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(SC.STUDENT_NO), 0)::NUMERIC, 2) AS PASS_RATE
FROM
    STUDENT_MST S
    LEFT JOIN SCORE_REC SC ON S.STUDENT_NO = SC.STUDENT_NO
WHERE
    S.DELETE_FLG = 0
GROUP BY
    S.STUDENT_NO,
    S.STUDENT_NAME,
    S.GRADE,
    S.CLASS_NO

;





CREATE OR REPLACE VIEW V_SCORE_RANK AS
SELECT
    GRADE,
    CLASS_NO,
    STUDENT_NO,
    STUDENT_NAME,
    TOTAL_SCORE,
    AVG_SCORE,
    RANK() OVER (PARTITION BY GRADE, CLASS_NO ORDER BY TOTAL_SCORE DESC) AS CLASS_RANK,
    RANK() OVER (PARTITION BY GRADE ORDER BY TOTAL_SCORE DESC) AS GRADE_RANK,
    DENSE_RANK() OVER (PARTITION BY GRADE, CLASS_NO ORDER BY TOTAL_SCORE DESC) AS CLASS_DENSE_RANK,
    ROW_NUMBER() OVER (PARTITION BY GRADE, CLASS_NO ORDER BY TOTAL_SCORE DESC, STUDENT_NO) AS ROW_RANK,
    NTILE(4) OVER (PARTITION BY GRADE, CLASS_NO ORDER BY TOTAL_SCORE DESC) AS QUARTILE,
    LAG(STUDENT_NAME, 1) OVER (PARTITION BY GRADE, CLASS_NO ORDER BY TOTAL_SCORE DESC) AS PREV_STUDENT,
    LEAD(STUDENT_NAME, 1) OVER (PARTITION BY GRADE, CLASS_NO ORDER BY TOTAL_SCORE DESC) AS NEXT_STUDENT,
    SUM(TOTAL_SCORE) OVER (PARTITION BY GRADE, CLASS_NO) AS CLASS_TOTAL,
    AVG(TOTAL_SCORE) OVER (PARTITION BY GRADE, CLASS_NO) AS CLASS_AVG,
    TOTAL_SCORE - AVG(TOTAL_SCORE) OVER (PARTITION BY GRADE, CLASS_NO) AS DIFF_FROM_AVG,
    PASS_RATE
FROM
    V_STUDENT_STATS

;





CREATE OR REPLACE VIEW V_SUBJECT_STATS AS
SELECT
    SB.SUBJECT_CD,
    SB.SUBJECT_NAME,
    SB.SUBJECT_TYPE,
    COUNT(SC.STUDENT_NO) AS STUDENT_COUNT,
    AVG(SC.SCORE) AS AVG_SCORE,
    MAX(SC.SCORE) AS MAX_SCORE,
    MIN(SC.SCORE) AS MIN_SCORE,
    STDDEV(SC.SCORE) AS SCORE_STDDEV,
    SUM(CASE WHEN SC.IS_PASS = 1 THEN 1 ELSE 0 END) AS PASS_COUNT,
    SUM(CASE WHEN SC.IS_PASS = 0 THEN 1 ELSE 0 END) AS FAIL_COUNT,
    ROUND(SUM(CASE WHEN SC.IS_PASS = 1 THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(SC.STUDENT_NO), 0)::NUMERIC, 2) AS PASS_RATE,
    PERCENT_RANK() OVER (ORDER BY AVG(SC.SCORE)) AS SCORE_PERCENTILE,
    CUME_DIST() OVER (ORDER BY AVG(SC.SCORE)) AS CUMULATIVE_DIST
FROM
    SUBJECT_MST SB
    LEFT JOIN SCORE_REC SC ON SB.SUBJECT_CD = SC.SUBJECT_CD
WHERE
    SB.DELETE_FLG = 0
GROUP BY
    SB.SUBJECT_CD, SB.SUBJECT_NAME, SB.SUBJECT_TYPE

;





CREATE OR REPLACE VIEW V_TEACHER_STATS AS
SELECT
    T.TEACHER_CD,
    T.TEACHER_NAME,
    T.DEPT_CD,
    COUNT(DISTINCT SB.SUBJECT_CD) AS SUBJECT_COUNT,
    COUNT(SC.STUDENT_NO) AS STUDENT_COUNT,
    AVG(SC.SCORE) AS AVG_SCORE,
    SUM(CASE WHEN SC.IS_PASS = 1 THEN 1 ELSE 0 END) AS PASS_COUNT,
    ROUND(SUM(CASE WHEN SC.IS_PASS = 1 THEN 1 ELSE 0 END) * 100.0 / NULLIF(COUNT(SC.STUDENT_NO), 0)::NUMERIC, 2) AS PASS_RATE
FROM
    TEACHER_MST T
    LEFT JOIN SUBJECT_MST SB ON T.TEACHER_CD = SB.TEACHER_CD
    LEFT JOIN SCORE_REC SC ON SB.SUBJECT_CD = SC.SUBJECT_CD
WHERE
    T.DELETE_FLG = 0
    AND SB.DELETE_FLG = 0
GROUP BY
    T.TEACHER_CD, T.TEACHER_NAME, T.DEPT_CD

;





CREATE OR REPLACE VIEW V_DEPENDENCY_GRAPH AS
SELECT
    'STUDENT_MST' AS TABLE_NAME,
    'SCORE_REC' AS DEPENDENT_TABLE,
    COUNT(*) AS DEPENDENCY_COUNT
FROM SCORE_REC



UNION ALL


SELECT
    'SUBJECT_MST' AS TABLE_NAME,
    'SCORE_REC' AS DEPENDENT_TABLE,
    COUNT(*) AS DEPENDENCY_COUNT
FROM SCORE_REC



UNION ALL


SELECT
    'SUBJECT_MST' AS TABLE_NAME,
    'TEACHER_MST' AS DEPENDENT_TABLE,
    COUNT(*) AS DEPENDENCY_COUNT
FROM SUBJECT_MST
WHERE TEACHER_CD IS NOT NULL


;
CREATE OR REPLACE VIEW V_STUDENT_WITH_SCORE AS
SELECT
    S.STUDENT_NO,
    S.STUDENT_NAME,
    S.GRADE,
    S.CLASS_NO,
    COALESCE(SUM(SC.SCORE), 0) AS TOTAL_SCORE
FROM STUDENT_MST S
  LEFT JOIN SCORE_REC SC
    ON S.STUDENT_NO = SC.STUDENT_NO
GROUP BY
    S.STUDENT_NO, S.STUDENT_NAME, S.GRADE, S.CLASS_NO

;