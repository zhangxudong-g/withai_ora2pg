-- 说明: 学生信息主表
-- 版本: 1.0.000
-- ============================================================================
CREATE TABLE STUDENT_MST (
 STUDENT_NO BIGINT NOT NULL,
 STUDENT_NAME VARCHAR(100) NOT NULL,
 STUDENT_KANA VARCHAR(200) NOT NULL,
 BIRTH_DATE BIGINT NOT NULL,
 GENDER BIGINT NOT NULL,
 GRADE BIGINT NOT NULL,
 CLASS_NO BIGINT NOT NULL,
 ADDRESS VARCHAR(500) ,
 PHONE VARCHAR(20) ,
 ENROLL_DATE BIGINT NOT NULL,
 GRADUATE_DATE BIGINT ,
 STATUS BIGINT DEFAULT 0,
 DELETE_FLG BIGINT DEFAULT 0,
 --
 REC_CREATE_TANTO_CD CHAR(12) ,
 REC_CREATE_DATE CHAR(23) ,
 REC_CREATE_WS VARCHAR(63) ,
 REC_UPDATE_TANTO_CD CHAR(12) ,
 REC_UPDATE_DATE CHAR(23) ,
 REC_UPDATE_WS VARCHAR(63) ,
 REC_UPDATE_KBN CHAR(2) ,
 CONSTRAINT STUDENT_MST_PK PRIMARY KEY (STUDENT_NO) 
)



;

COMMENT ON TABLE STUDENT_MST IS '学生信息主表';
CREATE INDEX STUDENT_MST_IDX1 ON STUDENT_MST(GRADE, CLASS_NO);

CREATE INDEX STUDENT_MST_IDX2 ON STUDENT_MST(STATUS, DELETE_FLG);