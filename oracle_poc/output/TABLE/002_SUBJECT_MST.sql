-- ============================================================================
-- 表名: SUBJECT_MST - 科目信息主表
-- 表名: TEACHER_MST - 教师信息主表 
-- 表名: SCORE_REC - 成绩记录表
-- ============================================================================

-- 科目表
CREATE TABLE SUBJECT_MST (
 SUBJECT_CD BIGINT NOT NULL,
 SUBJECT_NAME VARCHAR(100) NOT NULL,
 SUBJECT_KANA VARCHAR(200) NOT NULL,
 SUBJECT_TYPE BIGINT NOT NULL,
 CREDIT BIGINT DEFAULT 0,
 MAX_SCORE BIGINT DEFAULT 100,
 PASS_SCORE BIGINT DEFAULT 60,
 TEACHER_CD BIGINT ,
 SEMESTER BIGINT ,
 DELETE_FLG BIGINT DEFAULT 0,
 REC_CREATE_TANTO_CD CHAR(12),
 REC_CREATE_DATE CHAR(23),
 REC_CREATE_WS VARCHAR(63),
 REC_UPDATE_TANTO_CD CHAR(12),
 REC_UPDATE_DATE CHAR(23),
 REC_UPDATE_WS VARCHAR(63),
 REC_UPDATE_KBN CHAR(2),
 CONSTRAINT SUBJECT_MST_PK PRIMARY KEY (SUBJECT_CD) 
) ;

-- 教师表
CREATE TABLE TEACHER_MST (
 TEACHER_CD BIGINT NOT NULL,
 TEACHER_NAME VARCHAR(100) NOT NULL,
 TEACHER_KANA VARCHAR(200) NOT NULL,
 GENDER BIGINT NOT NULL,
 DEPT_CD BIGINT ,
 PHONE VARCHAR(20) ,
 EMAIL VARCHAR(100) ,
 HIRE_DATE BIGINT ,
 STATUS BIGINT DEFAULT 0,
 DELETE_FLG BIGINT DEFAULT 0,
 REC_CREATE_TANTO_CD CHAR(12),
 REC_CREATE_DATE CHAR(23),
 REC_UPDATE_TANTO_CD CHAR(12),
 REC_UPDATE_DATE CHAR(23),
 CONSTRAINT TEACHER_MST_PK PRIMARY KEY (TEACHER_CD) 
) ;

-- 成绩表
CREATE TABLE SCORE_REC (
 STUDENT_NO BIGINT NOT NULL,
 SUBJECT_CD BIGINT NOT NULL,
 EXAM_DATE BIGINT NOT NULL,
 EXAM_TYPE BIGINT NOT NULL,
 SCORE NUMERIC(5,2) ,
 SCORE_RANK BIGINT ,
 GRADE_LEVEL BIGINT ,
 IS_PASS BIGINT ,
 REMARK VARCHAR(500) ,
 REC_CREATE_TANTO_CD CHAR(12),
 REC_CREATE_DATE CHAR(23),
 REC_CREATE_WS VARCHAR(63),
 REC_UPDATE_TANTO_CD CHAR(12),
 REC_UPDATE_DATE CHAR(23),
 REC_UPDATE_WS VARCHAR(63),
 REC_UPDATE_KBN CHAR(2),
 CONSTRAINT SCORE_REC_PK PRIMARY KEY (STUDENT_NO, SUBJECT_CD, EXAM_DATE, EXAM_TYPE) 
) ;

-- 工作表
CREATE TABLE WK_SCORE_REPORT (
 ROW_NO BIGINT NOT NULL,
 NO BIGINT ,
 NENDO VARCHAR(1000) ,
 STUDENT_NO VARCHAR(1000) ,
 STUDENT_NAME VARCHAR(1000) ,
 STUDENT_KANA VARCHAR(1000) ,
 GENDER VARCHAR(1000) ,
 GRADE VARCHAR(1000) ,
 CLASS_NO VARCHAR(1000) ,
 SUBJECT_NAME VARCHAR(1000) ,
 SUBJECT_CD VARCHAR(1000) ,
 TOTAL_SCORE VARCHAR(1000) ,
 AVERAGE_SCORE VARCHAR(1000) ,
 PASS_COUNT VARCHAR(1000) ,
 FAIL_COUNT VARCHAR(1000) ,
 WSNUM VARCHAR(63) ,
 BATCHKBN BIGINT ,
 JOBNUM BIGINT ,
 CONSTRAINT WK_SCORE_REPORT_PK PRIMARY KEY (ROW_NO) 
) ;

-- 配置表
CREATE TABLE SYSTEM_CONFIG (
 CONFIG_CD VARCHAR(100) NOT NULL,
 CONFIG_NAME VARCHAR(200) NOT NULL,
 CONFIG_VALUE VARCHAR(1000) ,
 CONFIG_TYPE BIGINT DEFAULT 1,
 SORT_ORDER BIGINT DEFAULT 0,
 DESCRIPTION VARCHAR(500) ,
 DELETE_FLG BIGINT DEFAULT 0,
 CONSTRAINT SYSTEM_CONFIG_PK PRIMARY KEY (CONFIG_CD) 
) ;

-- 附件表(BYTEA)
CREATE TABLE ATTACHMENT_STORAGE (
 ROW_NUMBER BIGINT NOT NULL,
 DATA BYTEA ,
 FILE_ID VARCHAR(255) ,
 FILE_NAME VARCHAR(255) NOT NULL,
 FILE_SIZE BIGINT ,
 FILE_TYPE VARCHAR(100) ,
 FILE_UPDATE_TIME CHAR(23) ,
 CONSTRAINT ATTACHMENT_STORAGE_PK PRIMARY KEY (ROW_NUMBER) 
) ;

-- 日志表
CREATE TABLE PROCESS_LOG (
 LOG_ID BIGINT NOT NULL,
 JOBNUM BIGINT ,
 PROCESS_NAME VARCHAR(100) ,
 STEP_NO BIGINT ,
 LOG_LEVEL BIGINT DEFAULT 0,
 LOG_MESSAGE VARCHAR(2000) ,
 SQLCODE BIGINT ,
 SQLERRM VARCHAR(500) ,
 TANTO_CD CHAR(12) ,
 WS_NUM VARCHAR(63) ,
 LOG_DATE CHAR(23) ,
 CONSTRAINT PROCESS_LOG_PK PRIMARY KEY (LOG_ID) 
) ;

-- 临时表(批次处理用)
CREATE TEMPORARY TABLE TEMP_SCORE_BATCH (
 BATCH_ID BIGINT NOT NULL,
 STUDENT_NO BIGINT NOT NULL,
 SUBJECT_CD BIGINT NOT NULL,
 SCORE NUMERIC(5,2) ,
 STATUS BIGINT DEFAULT 0,
 ERROR_MSG VARCHAR(500) ,
 CONSTRAINT TEMP_SCORE_BATCH_PK PRIMARY KEY (BATCH_ID) 
) ON COMMIT PRESERVE ROWS ;