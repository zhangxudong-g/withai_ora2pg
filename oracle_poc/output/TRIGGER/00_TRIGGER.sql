CREATE OR REPLACE FUNCTION TRG_STUDENT_BI() RETURNS TRIGGER AS $$
DECLARE vMAX_STUDENT_NO BIGINT;
BEGIN

    
    IF NEW.STUDENT_NO IS NULL OR NEW.STUDENT_NO = 0 THEN
        SELECT COALESCE(MAX(STUDENT_NO), 10000) + 1
        INTO vMAX_STUDENT_NO
        FROM STUDENT_MST;
        NEW.STUDENT_NO := vMAX_STUDENT_NO;
    END IF;

    
    NEW.REC_CREATE_DATE := TO_CHAR(CURRENT_TIMESTAMP, 'YYYY/MM/DD HH24:MI:SS.MS');
    NEW.REC_UPDATE_DATE := TO_CHAR(CURRENT_TIMESTAMP, 'YYYY/MM/DD HH24:MI:SS.MS');
    
    
    IF NEW.STATUS IS NULL THEN
        NEW.STATUS := 0;
    END IF;
    IF NEW.DELETE_FLG IS NULL THEN
        NEW.DELETE_FLG := 0;
    END IF;
    RETURN NEW;

END;
$$ LANGUAGE plpgsql;

