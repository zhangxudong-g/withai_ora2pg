CREATE OR REPLACE FUNCTION TRG_SCORE_BIU() RETURNS TRIGGER AS $$
DECLARE vPASS_SCORE BIGINT := 60;
    _p25_msg TEXT;
    _p25_sqlstate TEXT;
BEGIN

    
    BEGIN
        SELECT COALESCE(PASS_SCORE, 60)
        INTO vPASS_SCORE
        FROM SUBJECT_MST
        WHERE SUBJECT_CD = NEW.SUBJECT_CD;
    EXCEPTION
        WHEN OTHERS THEN
            GET STACKED DIAGNOSTICS _p25_msg = MESSAGE_TEXT;
            RAISE EXCEPTION 'ORA: %', _p25_msg;
    END;


    
    IF NEW.SCORE IS NOT NULL THEN
        IF NEW.SCORE >= vPASS_SCORE THEN
            NEW.IS_PASS := 1;
        ELSE
            NEW.IS_PASS := 0;
        END IF;

        
        IF NEW.SCORE >= 90 THEN
            NEW.GRADE_LEVEL := 1;  
        ELSIF NEW.SCORE >= 80 THEN
            NEW.GRADE_LEVEL := 2;  
        ELSIF NEW.SCORE >= 70 THEN
            NEW.GRADE_LEVEL := 3;  
        ELSIF NEW.SCORE >= 60 THEN
            NEW.GRADE_LEVEL := 4;  
        ELSE
            NEW.GRADE_LEVEL := 5;  
        END IF;
    END IF;

    
    NEW.REC_UPDATE_DATE := TO_CHAR(CURRENT_TIMESTAMP, 'YYYY/MM/DD HH24:MI:SS.MS');
    RETURN NEW;

END;
$$ LANGUAGE plpgsql;

