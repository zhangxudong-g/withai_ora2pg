CREATE TYPE SCORE_RECORD AS (
    CNT             NUMERIC,                   
    NAIYOU          VARCHAR(1000),           
    KBN             NUMERIC,                                          
    STUDENT_NO      BIGINT,              
    SUBJECT_CD      BIGINT,               
    SCORE           NUMERIC(5,2),             
    GRADE_LEVEL     BIGINT,             
    IS_PASS         BIGINT);

CREATE OR REPLACE FUNCTION GET_STATUS_of_SCORE_RECORD(i_self SCORE_RECORD)
RETURNS VARCHAR
LANGUAGE plpgsql
AS $$
BEGIN
        IF i_self.IS_PASS = 1 THEN
            RETURN '合格';
        ELSE
            RETURN '不合格';
        END IF;
END;
$$;


CREATE OR REPLACE FUNCTION GET_LETTER_GRADE_of_SCORE_RECORD(i_self SCORE_RECORD)
RETURNS VARCHAR
LANGUAGE plpgsql
AS $$
BEGIN
        IF i_self.SCORE >= 90 THEN
            RETURN 'A';
        ELSIF i_self.SCORE >= 80 THEN
            RETURN 'B';
        ELSIF i_self.SCORE >= 70 THEN
            RETURN 'C';
        ELSIF i_self.SCORE >= 60 THEN
            RETURN 'D';
        ELSE
            RETURN 'F';
        END IF;
END;
$$;



CREATE TYPE SCORE_LIST AS (items SCORE_RECORD[]);

CREATE TYPE STUDENT_RECORD AS (
    STUDENT_NO      BIGINT,
    STUDENT_NAME    VARCHAR(100),
    STUDENT_KANA    VARCHAR(200),
    GENDER          BIGINT,
    GRADE           BIGINT,
    CLASS_NO        BIGINT,
    BIRTH_DATE      BIGINT,
    TOTAL_SCORE     NUMERIC(10,2),
    AVG_SCORE       NUMERIC(5,2),
    RANK_NO         BIGINT);

CREATE OR REPLACE FUNCTION GET_AGE_of_STUDENT_RECORD(i_self STUDENT_RECORD)
RETURNS NUMERIC
LANGUAGE plpgsql
AS $$
DECLARE
vBIRTH_YEAR NUMERIC;
        vNOW_YEAR NUMERIC;
    BEGIN
        vBIRTH_YEAR := (SUBSTRING((i_self.BIRTH_DATE)::varchar FROM 1 FOR 4))::NUMERIC;
        vNOW_YEAR := (TO_CHAR(CURRENT_TIMESTAMP, 'YYYY'))::NUMERIC;
        RETURN vNOW_YEAR - vBIRTH_YEAR;
END;
$$;


CREATE OR REPLACE FUNCTION GET_GENDER_NAME_of_STUDENT_RECORD(i_self STUDENT_RECORD)
RETURNS VARCHAR
LANGUAGE plpgsql
AS $$
BEGIN
        IF i_self.GENDER = 1 THEN
            RETURN '男';
        ELSIF i_self.GENDER = 2 THEN
            RETURN '女';
        ELSE
            RETURN '未知';
        END IF;
END;
$$;


CREATE OR REPLACE FUNCTION GET_RANK_STR_of_STUDENT_RECORD(i_self STUDENT_RECORD)
RETURNS VARCHAR
LANGUAGE plpgsql
AS $$
BEGIN
        RETURN (i_self.RANK_NO)::varchar || '位';
END;
$$;



